import './config.mjs';
import express from 'express';
import { readFile } from 'node:fs/promises';
import { renderDocument } from './ssr.mjs';
import { render, staticPath } from '../dist/server/entry-server.js';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createPool } from './db.mjs';
import { createApi } from './app.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.env.NODE_ENV ||= 'production';
const pool = createPool(process.env);
const staticBodies = JSON.parse(await readFile(path.join(root, 'dist/server/static-pages.json'), 'utf8'));
const app = express();
app.use('/api', createApi({ pool, env: process.env }));
app.use('/server', (req, res) => res.sendStatus(404));
app.use(express.static(path.join(root, 'dist'), { index: false }));
app.get('/{*path}', async (req, res) => {
  const html = await readFile(path.join(root, 'dist/server/template.html'), 'utf8');
  const pathname = staticPath(req.path);
  const staticPage = pathname === null ? undefined : { pathname, body: staticBodies[pathname] };
  if (staticPage && typeof staticPage.body !== 'string') throw new Error('Static page is missing. Rebuild the application.');
  res.set('Cache-Control', 'no-store').type('html').send(await renderDocument(html, req.path, pool, render, staticPage));
});
const server = app.listen(Number(process.env.PORT || 4000), process.env.HOST || '127.0.0.1', () => console.log('BrightByte application server is running.'));
const stop = () => server.close(async () => { await pool.end(); process.exit(0); });
process.on('SIGTERM',stop); process.on('SIGINT',stop);
